// Regenerates src/api/schema.d.ts from a running server's OpenAPI document (Development environment only).
// Usage: npm run gen:api [-- https://host:port]
import { get } from "node:https";
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const server = process.argv[2] ?? process.env.PANEL_API ?? "https://localhost:7114";
const output = new URL("../src/api/schema.d.ts", import.meta.url);

// The development server uses a self-signed certificate
const fetchJson = url => new Promise((resolve, reject) => {
  get(url, { rejectUnauthorized: false }, response => {
    if (response.statusCode !== 200) {
      reject(new Error(`${url} answered ${response.statusCode}; is the server running in Development?`));
      response.resume();
      return;
    }
    let body = "";
    response.setEncoding("utf8");
    response.on("data", chunk => (body += chunk));
    response.on("end", () => resolve(JSON.parse(body)));
  }).on("error", reject);
});

const document = await fetchJson(`${server}/openapi/v1.json`);
const ast = await openapiTS(document);
await writeFile(output, "// Generated by scripts/gen-api.mjs from the server's OpenAPI document. Do not edit.\n" + astToString(ast));
console.log(`Wrote ${output.pathname}`);
