using System.ComponentModel.DataAnnotations;
using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.Extensions.DependencyInjection;
using Server.Database;
using Server.Database.PostgreSql;
using Server.Infrastructure.Database;
using Server.Infrastructure.Options;
using Xunit;

namespace Server.Infrastructure.Tests.Database;

public class DatabaseProviderTests
{
    [Fact]
    public void DefaultSettingsKeepExistingSqlitePathAndMigrations()
    {
        var options = new DbContextOptionsBuilder<ServerDbContext>();
        options.UseServerDatabase(new DatabaseOptions(), new StorageOptions { Directory = "existing-data" });
        using var context = new ServerDbContext(options.Options);
        Assert.True(context.Database.IsSqlite());
        Assert.Equal(Path.Combine("existing-data", "server.db"),
            new SqliteConnectionStringBuilder(context.Database.GetConnectionString()).DataSource);
        Assert.Contains("20261020182442_Initial", context.Database.GetMigrations());
        Assert.False(context.Database.HasPendingModelChanges());
    }

    [Theory]
    [InlineData(DatabaseProvider.PostgreSql, null)]
    [InlineData(DatabaseProvider.PostgreSql, "Data Source=server.db")]
    [InlineData(DatabaseProvider.PostgreSql, "Username=test")]
    [InlineData(DatabaseProvider.Sqlite, "Host=localhost")]
    [InlineData((DatabaseProvider)99, null)]
    public void InvalidSettingsFailBeforeConnecting(DatabaseProvider provider, string? connectionString)
    {
        var options = new DbContextOptionsBuilder<ServerDbContext>();
        Assert.Throws<ValidationException>(() => options.UseServerDatabase(
            new DatabaseOptions { Provider = provider, ConnectionString = connectionString }, new StorageOptions()));
    }

    [Fact]
    public void PostgreSqlUsesOnlyItsOwnMigrationsAndCurrentModel()
    {
        var options = new DbContextOptionsBuilder<ServerDbContext>();
        options.UseServerDatabase(new DatabaseOptions
        {
            Provider = DatabaseProvider.PostgreSql,
            ConnectionString = "Host=localhost;Database=flowrate;Username=test"
        }, new StorageOptions());
        using var context = new ServerDbContext(options.Options);
        Assert.True(context.Database.IsNpgsql());
        Assert.Equal(typeof(PostgreSqlDatabase).Assembly,
            context.GetService<Microsoft.EntityFrameworkCore.Migrations.IMigrationsAssembly>().Assembly);
        Assert.DoesNotContain("20261020182442_Initial", context.Database.GetMigrations());
        Assert.False(context.Database.HasPendingModelChanges());
        var script = context.GetService<Microsoft.EntityFrameworkCore.Migrations.IMigrator>().GenerateScript();
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", script);
        Assert.Contains("timestamp with time zone", script);
        Assert.DoesNotContain("PRAGMA", script);
        Assert.DoesNotContain("normalize_ip", script);
    }

    [Fact]
    public async Task SqliteInitializerUsesExplicitConnectionString()
    {
        var directory = Path.Combine(Path.GetTempPath(), "flowrate-provider-" + Guid.NewGuid().ToString("N"));
        var path = Path.Combine(directory, "custom.db");
        var services = new ServiceCollection();
        services.AddPooledDbContextFactory<ServerDbContext>(options => options.UseServerDatabase(
            new DatabaseOptions { ConnectionString = $"Data Source={path};Pooling=False" },
            new StorageOptions { Directory = Path.Combine(directory, "unused") }));
        try
        {
            await using var provider = services.BuildServiceProvider();
            await provider.InitializeDatabaseAsync();
            await provider.InitializeDatabaseAsync();
            Assert.True(File.Exists(path));
            Assert.False(Directory.Exists(Path.Combine(directory, "unused")));
            await using var context = await provider.GetRequiredService<IDbContextFactory<ServerDbContext>>().CreateDbContextAsync();
            Assert.Empty(await context.Database.GetPendingMigrationsAsync());
        }
        finally
        {
            if (Directory.Exists(directory))
                Directory.Delete(directory, recursive: true);
        }
    }
}
