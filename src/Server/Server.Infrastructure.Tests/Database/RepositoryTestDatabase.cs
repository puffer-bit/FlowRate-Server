using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using Server.Database;
using Server.Infrastructure.Database;
using Server.Infrastructure.Options;

namespace Server.Infrastructure.Tests.Database;

/// <summary>Each test owns a SQLite file or a newly created PostgreSQL schema.</summary>
internal sealed class RepositoryTestDatabase : IDisposable, IDbContextFactory<ServerDbContext>
{
    private readonly string? _sqlitePath;
    private readonly string? _adminConnectionString;
    private readonly string? _schema;
    public DbContextOptions<ServerDbContext> Options { get; }

    public RepositoryTestDatabase()
    {
        var provider = Environment.GetEnvironmentVariable("FLOWRATE_TEST_DATABASE_PROVIDER") ?? "Sqlite";
        if (!Enum.TryParse<DatabaseProvider>(provider, ignoreCase: true, out var selected) || !Enum.IsDefined(selected))
            throw new InvalidOperationException("FLOWRATE_TEST_DATABASE_PROVIDER must be Sqlite or PostgreSql.");
        var builder = new DbContextOptionsBuilder<ServerDbContext>();
        string connectionString;
        if (selected == DatabaseProvider.PostgreSql)
        {
            var configured = Environment.GetEnvironmentVariable("FLOWRATE_TEST_POSTGRES_CONNECTION_STRING");
            if (string.IsNullOrWhiteSpace(configured))
                throw new InvalidOperationException("PostgreSQL tests require FLOWRATE_TEST_POSTGRES_CONNECTION_STRING.");
            var admin = new NpgsqlConnectionStringBuilder(configured) { Pooling = false };
            _adminConnectionString = admin.ConnectionString;
            _schema = "flowrate_test_" + Guid.NewGuid().ToString("N");
            using var connection = new NpgsqlConnection(_adminConnectionString);
            connection.Open();
            using var command = new NpgsqlCommand($"CREATE SCHEMA \"{_schema}\"", connection);
            command.ExecuteNonQuery();
            admin.SearchPath = _schema;
            connectionString = admin.ConnectionString;
        }
        else
        {
            _sqlitePath = Path.Combine(Path.GetTempPath(), $"flowrate-repository-{Guid.NewGuid():N}.db");
            connectionString = new SqliteConnectionStringBuilder { DataSource = _sqlitePath, Pooling = false }.ConnectionString;
        }
        builder.UseServerDatabase(new DatabaseOptions { Provider = selected, ConnectionString = connectionString }, new StorageOptions());
        Options = builder.Options;
    }

    public ServerDbContext CreateDbContext() => new(Options);

    public void Dispose()
    {
        if (_schema != null)
        {
            // The schema name is generated by this instance, never supplied by the caller.
            using var connection = new NpgsqlConnection(_adminConnectionString);
            connection.Open();
            using var command = new NpgsqlCommand($"DROP SCHEMA \"{_schema}\" CASCADE", connection);
            command.ExecuteNonQuery();
        }
        else if (_sqlitePath != null)
        {
            File.Delete(_sqlitePath);
            File.Delete(_sqlitePath + "-wal");
            File.Delete(_sqlitePath + "-shm");
        }
    }
}
